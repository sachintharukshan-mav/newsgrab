/**
 * Computes price history statistics for a given fuel product key
 */
export function getProductStats(key: FuelSeriesKey) {
  const validRecords = CEYPETCO_HISTORICAL_RECORDS
    .filter((r) => r[key] !== null && typeof r[key] === 'number')
    .map((r) => ({ date: r.isoDate, price: r[key] as number, sortKey: r.sortKey }));

  if (validRecords.length === 0) {
    return {
      current: 0,
      allTimeHigh: { price: 0, date: '' },
      allTimeLow: { price: 0, date: '' },
      oneYearChange: 0,
      oneYearPercent: 0,
      fiveYearChange: 0,
      fiveYearPercent: 0,
      totalRevisions: 0,
    };
  }

  const latest = validRecords[0];
  let high = validRecords[0];
  let low = validRecords[0];

  for (const r of validRecords) {
    if (r.price > high.price) high = r;
    if (r.price < low.price) low = r;
  }

  // Find 1-year ago (approx 365 days)
  const oneYearAgoSortKey = latest.sortKey - 10000;
  const oneYearRecord = validRecords.find((r) => r.sortKey <= oneYearAgoSortKey) || validRecords[validRecords.length - 1];

  // Find 5-year ago
  const fiveYearsAgoSortKey = latest.sortKey - 50000;
  const fiveYearRecord = validRecords.find((r) => r.sortKey <= fiveYearsAgoSortKey) || validRecords[validRecords.length - 1];

  const oneYearDiff = latest.price - oneYearRecord.price;
  const oneYearPct = (oneYearDiff / oneYearRecord.price) * 100;

  const fiveYearDiff = latest.price - fiveYearRecord.price;
  const fiveYearPct = (fiveYearDiff / fiveYearRecord.price) * 100;

  return {
    current: latest.price,
    allTimeHigh: { price: high.price, date: high.date },
    allTimeLow: { price: low.price, date: low.date },
    oneYearChange: oneYearDiff,
    oneYearPercent: oneYearPct,
    fiveYearChange: fiveYearDiff,
    fiveYearPercent: fiveYearPct,
    totalRevisions: validRecords.length,
  };
}

/**
 * Filter time-series points by date range
 */
export function getTimeSeriesForRange(
  key: FuelSeriesKey,
  range: '1Y' | '3Y' | '5Y' | '10Y' | 'ALL' = 'ALL'
) {
  // Sort ascending for charting (left to right)
  const sorted = [...CEYPETCO_HISTORICAL_RECORDS]
    .filter((r) => r[key] !== null)
    .sort((a, b) => a.sortKey - b.sortKey);

  if (sorted.length === 0) return [];

  const latestSortKey = sorted[sorted.length - 1].sortKey;
  let minSortKey = 0;

  if (range === '1Y') minSortKey = latestSortKey - 10000;
  else if (range === '3Y') minSortKey = latestSortKey - 30000;
  else if (range === '5Y') minSortKey = latestSortKey - 50000;
  else if (range === '10Y') minSortKey = latestSortKey - 100000;

  return sorted
    .filter((r) => r.sortKey >= minSortKey)
    .map((r) => ({
      date: r.dateLabel,
      isoDate: r.isoDate,
      year: r.year,
      price: r[key] as number,
    }));
}
